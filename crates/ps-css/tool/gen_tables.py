#!/usr/bin/env python3
"""Generate Rust enum tables from css_parser gperf + color tables.

Usage: gen_tables.py <css_parser/src> <out_dir>
Writes identifier_gen.rs, property_gen.rs, colors_gen.rs fragments.
Fails loudly on coverage drift (enum vars missing from gperf or vice
versa, except the three known dead Identifier variants).
"""

import re
import sys

SRC, OUT = sys.argv[1], sys.argv[2]

# Known-dead Identifier variants with no gperf entry (never constructed;
# C++ TextFromIdent would read uninitialized table slots for them).
DEAD_IDENTS = {"LTR": "ltr", "RTL": "rtl", "LOWER_LATIN": "lower-latin"}


def camel(name):
    return "".join(part[:1].upper() + part[1:].lower() for part in name.split("_"))


def gen_enum(gperf_path, header_path, kind, cls, matcher):
    gperf = open(f"{SRC}/{gperf_path}").read()
    entries = re.findall(
        r"^([^\s,][^,\n]*),\s*" + cls + r"::(\w+)\s*$", gperf, re.M)
    header = open(f"{SRC}/{header_path}").read()
    m = re.search(r"enum " + kind + r" \{(.*?)\};", header, re.S)
    enum_vars = [
        v for v in re.findall(r"^\s*(\w+),?\s*(?://.*)?$", m.group(1), re.M)
        if re.fullmatch(r"[A-Z0-9_]+", v)
    ]
    mapped = {v for _, v in entries}
    if cls == "Identifier":
        missing = [v for v in enum_vars if v not in mapped and v != "OTHER"
                   and v not in DEAD_IDENTS]
    else:
        missing = [v for v in enum_vars if v not in mapped and v != "OTHER"]
    assert not missing, f"{cls} enum vars missing from gperf: {missing}"
    extra = [v for v in mapped if v not in enum_vars]
    assert not extra, f"{cls} gperf vars missing from enum: {extra}"
    names = {var: text for text, var in entries}
    # Rust variant names must be unique after CamelCase conversion.
    variants = [camel(v) for v in enum_vars]
    assert len(set(variants)) == len(variants), "variant collision"
    lines = [
        f"// Generated by gen_tables.py from {gperf_path}; do not hand-edit.",
        f"#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]",
        f"pub enum {matcher} {{",
    ]
    for var in enum_vars:
        lines.append(f"    {camel(var)},")
    lines.append("}")
    lines.append("")
    lines.append(f"impl {matcher} {{")
    lines.append("    /// Classifies text (gperf `%ignore-case`: ASCII")
    lines.append("    /// case-insensitive).")
    lines.append(f"    pub fn from_text(text: &[u8]) -> {matcher} {{")
    lines.append("        match text.to_ascii_lowercase().as_slice() {")
    for text, var in entries:
        lines.append(f'            b"{text}" => {matcher}::{camel(var)},')
    # Dead variants are unreachable from text (no gperf entry).
    lines.append(f"            _ => {matcher}::Other,")
    lines.append("        }")
    lines.append("    }")
    lines.append("")
    lines.append("    pub fn text(self) -> &'static str {")
    lines.append("        match self {")
    for var in enum_vars:
        if var == "OTHER":
            lines.append(f'            {matcher}::Other => "OTHER",')
        elif var in DEAD_IDENTS:
            lines.append(
                f'            {matcher}::{camel(var)} => "{DEAD_IDENTS[var]}",')
        else:
            lines.append(f'            {matcher}::{camel(var)} => "{names[var]}",')
    lines.append("        }")
    lines.append("    }")
    lines.append("}")
    return "\n".join(lines) + "\n"


ident_rs = gen_enum("webutil/css/identifier.gperf", "webutil/css/identifier.h",
                   "Ident", "Identifier", "Ident")
prop_rs = gen_enum("webutil/css/property.gperf", "webutil/css/property.h",
                  "Prop", "Property", "Prop")
open(f"{OUT}/identifier_gen.rs", "w").write(ident_rs)
open(f"{OUT}/property_gen.rs", "w").write(prop_rs)


def gen_colors():
    src = open(f"{SRC}/webutil/html/htmlcolor.cc").read()
    table = re.search(r"known_color_values\[\] = \{(.*?)\};", src, re.S).group(1)
    vals = re.findall(r"/\*\s*\d+ (\w+) \*/\{([^}]*)\}", table)
    entries = re.findall(r'CaseEqual\("(\w+)", colorstr\)\) \{\s*return &known_color_values\[(\d+)\];', src)
    # Comment numbers are stale line numbers, not indices; index positionally.
    by_index = {i: (name, rgb) for i, (name, rgb) in enumerate(vals)}
    assert len(by_index) == len(vals), "dup table index"
    lines = ["// Generated by gen_tables.py from htmlcolor.cc; do not hand-edit.",
             "pub const NAMED_COLORS: &[(&str, (u8, u8, u8))] = &["]
    seen = set()
    for name, index in entries:
        index = int(index)
        assert index in by_index, f"index {index} missing"
        tname, rgb = by_index[index]
        assert tname == name, f"table/function mismatch: {tname} vs {name}"
        r, g, b = [int(x) for x in rgb.split(",")]
        lines.append(f'    ("{name}", ({r}, {g}, {b})),')
        seen.add(index)
    assert seen == set(by_index), f"table coverage drift: {set(by_index) - seen}"
    lines.append("];")
    return "\n".join(lines) + "\n"


def gen_system_colors():
    src = open(f"{SRC}/webutil/css/util.cc").read()
    table = re.search(r"known_system_color_values\[\] = \{(.*?)\};", src, re.S).group(1)
    vals = re.findall(r"/\* ?(\d+) (\w+) \*/\{([^}]*)\}", table)
    entries = re.findall(r'strcasecmp\("(\w+)", colorstr\)\) \{\s*return &known_system_color_values\[(\d+)\];', src)
    by_index = {int(i): (name, rgb) for i, name, rgb in vals}
    lines = ["pub const SYSTEM_COLORS: &[(&str, (u8, u8, u8))] = &["]
    seen = set()
    for name, index in entries:
        index = int(index)
        tname, rgb = by_index[index]
        assert tname == name, f"system mismatch: {tname} vs {name}"
        r, g, b = [int(x) for x in rgb.split(",")]
        lines.append(f'    ("{name}", ({r}, {g}, {b})),')
        seen.add(index)
    assert seen == set(by_index), "system coverage drift"
    lines.append("];")
    return "\n".join(lines) + "\n"


open(f"{OUT}/colors_gen.rs", "w").write(gen_colors() + "\n" + gen_system_colors())
print("generated identifier/property/colors tables")


def gen_tags():
    """HtmlTag enum + case-insensitive lookup (htmltagenum.h/index.cc)."""
    header = open(f"{SRC}/webutil/html/htmltagenum.h").read()
    enum_vars = re.findall(r"kHtmlTag(\w+)\s*=\s*(\d+)", header)
    index = open(f"{SRC}/webutil/html/htmltagindex.cc").read()
    body = index[index.index("switch (length) {"):]
    cur_len, entries = None, []
    for line in body.split("\n"):
        m = re.match(r"  case (\d+):", line)
        if m:
            cur_len = int(m.group(1))
            continue
        m = re.match(r"\s*case C\d\(([^)]*)\): return (kHtmlTag\w+);", line)
        if m and cur_len is not None:
            chars = re.findall(r"'(.)'", m.group(1))
            name = "".join(chars)
            assert len(name) == cur_len, (name, cur_len)
            entries.append((name, m.group(2)))
    entries += [("plaintext", "kHtmlTagPlaintext"),
                ("blockquote", "kHtmlTagBlockquote"),
                ("figcaption", "kHtmlTagFigcaption")]
    known = {f"kHtmlTag{v}" for v, _ in enum_vars}
    for _, enum in entries:
        assert enum in known, enum
    lines = ["// Generated by gen_tables.py from htmltagenum.h/index.cc.",
             "#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]",
             "#[repr(i32)]",
             "pub enum HtmlTag {"]
    for var, num in enum_vars:
        lines.append(f"    {var} = {num},")
    lines.append("}")
    lines.append("")
    lines.append("impl HtmlTag {")
    lines.append("    /// Case-insensitive builtin lookup (`FindHtmlTag`).")
    lines.append("    #[must_use]")
    lines.append("    pub fn find_builtin(tag: &[u8]) -> HtmlTag {")
    lines.append("        if tag.is_empty() {")
    lines.append("            return HtmlTag::ZeroLength;")
    lines.append("        }")
    lines.append("        let lower = tag.to_ascii_lowercase();")
    lines.append("        // Lengths 9-10 use if-chains (folded into the table),")
    lines.append("        // and any !doctype prefix / ! or ? lead is special.")
    lines.append("        if lower.len() >= 8 && lower[..8] == *b\"!doctype\" {")
    lines.append("            return HtmlTag::BangDoctype;")
    lines.append("        }")
    lines.append("        if lower[0] == b'!' || lower[0] == b'?' {")
    lines.append("            return HtmlTag::BogusComment;")
    lines.append("        }")
    lines.append("        match lower.as_slice() {")
    for name, enum in sorted(entries):
        lines.append(f'            b"{name}" => HtmlTag::{enum[len("kHtmlTag"):]},')
    lines.append("            _ => HtmlTag::Unknown,")
    lines.append("        }")
    lines.append("    }")
    lines.append("}")
    return "\n".join(lines) + "\n"


open(f"{OUT}/tags_gen.rs", "w").write(gen_tags())
print("generated tags table")
