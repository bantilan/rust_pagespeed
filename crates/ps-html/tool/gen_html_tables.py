#!/usr/bin/env python3
"""Generates ps-html keyword/escape tables from the C++ sources.

Reads (never modifies) the original mod_pagespeed tree and emits:
  crates/ps-html/src/name_generated.rs      Keyword enum + lookup + spellings
  crates/ps-html/src/keywords_generated.rs  entity tables + tag sets + relations

Usage: python3 tool/gen_html_tables.py /path/to/mod_pagespeed
"""
import re
import sys

SRC = sys.argv[1] if len(sys.argv) > 1 else "/home/gamingph/Projects/Rust/mod_pagespeed"


def read(path):
    with open(f"{SRC}/{path}") as f:
        return f.read()


def parse_gperf():
    entries = []
    for line in read("pagespeed/kernel/html/html_name.gperf").splitlines():
        m = re.match(r'\s*"([^"]+)",\s*HtmlName::(k\w+)', line)
        if m:
            entries.append((m.group(1), m.group(2)))
    return entries


def header_enum_order():
    """Authoritative discriminant order from html_name.h (not gperf order:
    kDataPagespeedOrigIndex/OrigSrc are swapped between the two)."""
    header = read("pagespeed/kernel/html/html_name.h")
    in_enum = False
    variants = []
    for line in header.splitlines():
        if "enum Keyword" in line:
            in_enum = True
            continue
        if in_enum:
            m = re.match(r"\s*(k\w+)", line)
            if m:
                variants.append(m.group(1))
            if "};" in line:
                break
    return variants


def check_enum_order(entries):
    variants = header_enum_order()
    expected = {v for _, v in entries} | {"kNotAKeyword"}
    assert set(variants) == expected, "enum/gperf set drift"
    assert variants[-1] == "kNotAKeyword", "kNotAKeyword must be last"


def rust_variant(cpp):
    assert cpp.startswith("k")
    return cpp[1:]


def gen_name(entries, out):
    order = header_enum_order()
    lines = [
        "//! GENERATED by tool/gen_html_tables.py — do not edit.",
        "//! Keyword enum (discriminants match C++ `HtmlName::Keyword` order),",
        "//! case-insensitive lookup, and canonical spellings.",
        "",
        "/// HTML tag/attribute keyword. Variant order matches the C++ enum so",
        "/// sorted-set membership tests behave identically.",
        "#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord)]",
        "#[repr(u16)]",
        "pub enum Keyword {",
    ]
    for variant in order:
        lines.append(f"    {rust_variant(variant)},")
    lines.append("}")
    lines.append("")
    # Lookup table sorted by lowercase spelling for binary search.
    table = sorted(((name.lower(), name, variant) for name, variant in entries))
    lines.append("/// (lowercase spelling, canonical spelling, keyword), sorted for search.")
    lines.append(f"const LOOKUP: [(&str, &str, Keyword); {len(table)}] = [")
    for lower, canon, variant in table:
        lines.append(f'    ("{lower}", "{canon}", Keyword::{rust_variant(variant)}),')
    lines.append("];")
    lines.append("")
    lines.append("/// Case-insensitive keyword lookup (`HtmlName::Lookup`).")
    lines.append("#[must_use]")
    lines.append("pub fn lookup(name: &[u8]) -> Keyword {")
    lines.append("    // Stack-lowercase short names; heap fallback for long ones.")
    lines.append("    let mut buf = [0u8; 64];")
    lines.append("    let lowered: &[u8] = if name.len() <= buf.len() {")
    lines.append("        for (slot, byte) in buf.iter_mut().zip(name.iter()) {")
    lines.append("            *slot = byte.to_ascii_lowercase();")
    lines.append("        }")
    lines.append("        &buf[..name.len()]")
    lines.append("    } else {")
    lines.append("        return lookup_heap(name);")
    lines.append("    };")
    lines.append("    match LOOKUP.binary_search_by(|entry| entry.0.as_bytes().cmp(lowered)) {")
    lines.append("        Ok(index) => LOOKUP[index].2,")
    lines.append("        Err(_) => Keyword::NotAKeyword,")
    lines.append("    }")
    lines.append("}")
    lines.append("")
    lines.append("fn lookup_heap(name: &[u8]) -> Keyword {")
    lines.append("    let lowered: Vec<u8> = name.iter().map(|b| b.to_ascii_lowercase()).collect();")
    lines.append(
        "    match LOOKUP.binary_search_by(|entry| entry.0.as_bytes().cmp(&lowered)) {"
    )
    lines.append("        Ok(index) => LOOKUP[index].2,")
    lines.append("        Err(_) => Keyword::NotAKeyword,")
    lines.append("    }")
    lines.append("}")
    lines.append("")
    lines.append("/// Canonical (lowercase) spelling (`KeywordToString`).")
    lines.append("#[must_use]")
    lines.append("pub const fn as_str(keyword: Keyword) -> Option<&'static str> {")
    lines.append("    match keyword {")
    for name, variant in entries:
        lines.append(f'        Keyword::{rust_variant(variant)} => Some("{name.lower()}"),')
    lines.append("        Keyword::NotAKeyword => None,")
    lines.append("    }")
    lines.append("}")
    lines.append("")
    open(out, "w").write("\n".join(lines))


def parse_escape_tables():
    src = read("pagespeed/kernel/html/html_keywords.cc")
    # Single-byte: { "Name", {0xXX, 0xYY?, 0x0} } — value bytes before 0x0.
    singles = []
    for m in re.finditer(
        r'\{\s*"([^"]+)",\s*\{((?:0x[0-9A-Fa-f]+,?\s*)+)\}\s*\}', src
    ):
        name = m.group(1)
        values = [int(v, 16) for v in re.findall(r"0x([0-9A-Fa-f]+)", m.group(2))]
        # Only the single-byte table has a trailing 0x0 sentinel with <=2 values.
        if values and values[-1] == 0 and len(values) <= 3:
            singles.append((name, values[:-1]))
    # Multi-byte: { "name", 1234 } — scoped to the array body only.
    m = re.search(
        r"kHtmlKeywordsSequencesMultiByte\[\] = \{(.*?)\};", src, re.DOTALL
    )
    assert m, "multibyte table"
    multis = [
        (e.group(1), int(e.group(2)))
        for e in re.finditer(r'\{\s*"([^"]+)",\s*(\d+)\s*\},', m.group(1))
    ]
    return singles, multis


def parse_tag_sets():
    lex = read("pagespeed/kernel/html/html_lexer.cc")
    kw_h = read("pagespeed/kernel/html/html_keywords.h")
    kw_cc = read("pagespeed/kernel/html/html_keywords.cc")

    def kw_array(src, name):
        m = re.search(
            rf"{name}\[\] = \{{(.*?)\}};", src, re.DOTALL
        )
        assert m, name
        return [
            v.replace("HtmlName::", "")
            for v in re.findall(r"HtmlName::k\w+", m.group(1))
        ]

    sets = {
        "LITERAL": kw_array(lex, "kLiteralTags"),
        "SOMETIMES_LITERAL": kw_array(lex, "kSometimesLiteralTags"),
        "IMPLICITLY_CLOSED": kw_array(lex, "kImplicitlyClosedHtmlTags"),
        "NON_BRIEF_TERMINATED": kw_array(lex, "kNonBriefTerminatedTags"),
    }

    def str_list(name):
        m = re.search(rf'{name}\[\] =\s*\n?\s*"([^"]*)"', kw_cc)
        assert m, name
        # Some span two literals; collect continuations.
        text = m.group(1)
        rest = kw_cc[m.end(): m.end() + 120]
        m2 = re.match(r'\s*"([^"]*)"', rest)
        if m2 and ";" not in rest[: rest.index('"', 1)]:
            pass
        return text.split()

    # kFormattingElements spans two string literals; handle explicitly.
    m = re.search(
        r"kFormattingElements\[\] =\n\s*\"([^\"]*)\"\n\s*\"([^\"]*)\"", kw_cc
    )
    formatting = (m.group(1) + m.group(2)).split() if m else []
    m = re.search(
        r"kParagraphTerminators\[\] =\n\s*\"([^\"]*)\"\n\s*\"([^\"]*)\"", kw_cc
    )
    terminators = (m.group(1) + m.group(2)).split() if m else []
    sets["TABLE_LEAVES"] = str_list("kTableLeaves")
    sets["TABLE_SECTIONS"] = str_list("kTableSections")
    sets["TABLE_ELEMENTS"] = str_list("kTableElements")
    sets["FORMATTING"] = formatting
    sets["LIST"] = str_list("kListElements")
    sets["DECLARATION_STR"] = str_list("kDeclarationElements")
    sets["PARAGRAPH_TERMINATORS"] = terminators
    # Optionally closed = formatting + fixed list + list + table elements.
    sets["OPTIONALLY_CLOSED"] = (
        formatting
        + "body colgroup dd dt html optgroup option p".split()
        + sets["LIST"]
        + sets["TABLE_ELEMENTS"]
    )
    return sets


def keyword_of(name, entries):
    table = {n.lower(): v for n, v in entries}
    key = name.lower()
    if key not in table:
        # Release-mode C++ inserts kNotAKeyword pairs (DCHECK-only guard):
        # "o:p" participates as NotAKeyword, which notably makes ANY two
        # unknown tags auto-close each other. Ported faithfully.
        assert key == "o:p", f"unknown tag in set: {name}"
        return "kNotAKeyword"
    return table[key]


def gen_keywords(singles, multis, sets, entries, out):
    order = {rust_variant(v): i for i, v in enumerate(header_enum_order())}
    lines = [
        "//! GENERATED by tool/gen_html_tables.py — do not edit.",
        "//! Entity tables, tag sets, and auto-close/contained relations.",
        "",
        "use crate::name::Keyword;",
        "",
        "/// Single-byte entity values: (name, value bytes).",
        f"pub const SINGLE_BYTE_ENTITIES: [(&str, &[u8]); {len(singles)}] = [",
    ]
    for name, values in singles:
        vals = ", ".join(f"0x{v:02x}" for v in values)
        lines.append(f'    ("{name}", &[{vals}]),')
    lines.append("];")
    lines.append("")
    lines.append("/// Multi-byte entities: (name, UCS-2 code point).")
    lines.append(f"pub const MULTI_BYTE_ENTITIES: [(&str, u16); {len(multis)}] = [")
    for name, code in multis:
        lines.append(f'    ("{name}", {code}),')
    lines.append("];")
    lines.append("")

    def emit_set(const_name, members):
        variants = [rust_variant(keyword_of(tag, entries)) for tag in members]
        lines.append(f"/// `{const_name.lower()}` tag set, sorted for binary search.")
        lines.append(
            f"pub const {const_name}: [Keyword; {len(variants)}] = ["
        )
        for variant in sorted(variants):
            lines.append(f"    Keyword::{variant},")
        lines.append("];")
        lines.append("")

    for const_name, key in [
        ("LITERAL_TAGS", "LITERAL"),
        ("SOMETIMES_LITERAL_TAGS", "SOMETIMES_LITERAL"),
        ("IMPLICITLY_CLOSED_TAGS", "IMPLICITLY_CLOSED"),
        ("NON_BRIEF_TERMINATED_TAGS", "NON_BRIEF_TERMINATED"),
    ]:
        # Sorted by discriminant (C++ operator<), NOT by name.
        variants = sorted((rust_variant(v) for v in sets[key]), key=order.__getitem__)
        lines.append(f"pub const {const_name}: [Keyword; {len(variants)}] = [")
        for variant in variants:
            lines.append(f"    Keyword::{variant},")
        lines.append("];")
        lines.append("")

    for const_name, key in [
        ("OPTIONALLY_CLOSED_TAGS", "OPTIONALLY_CLOSED"),
        ("DECLARATION_TAGS", "DECLARATION_STR"),
    ]:
        variants = sorted(
            {rust_variant(keyword_of(t, entries)) for t in sets[key]},
            key=order.__getitem__,
        )
        lines.append(f"pub const {const_name}: [Keyword; {len(variants)}] = [")
        for variant in variants:
            lines.append(f"    Keyword::{variant},")
        lines.append("];")
        lines.append("")

    # Auto-close pairs: expand the AddAutoClose/AddContained calls.
    auto_close = []
    contained = []

    def expand(space_list):
        return space_list

    leaves = sets["TABLE_LEAVES"]
    sections = sets["TABLE_SECTIONS"]
    formatting = sets["FORMATTING"]
    lists = sets["LIST"]
    for a in leaves:
        for b in leaves:
            auto_close.append((a, b))
    for a in leaves:
        auto_close.append((a, "tr"))
    for b in sections:
        auto_close.append(("tr", b))
    auto_close.append(("tr", "tr"))
    for a in sections:
        for b in sections:
            auto_close.append((a, b))
    for b in sets["PARAGRAPH_TERMINATORS"]:
        auto_close.append(("p", b))
    auto_close.append(("li", "li"))
    for a in ["dd", "dt"]:
        for b in ["dd", "dt"]:
            auto_close.append((a, b))
    for a in ["rp", "rt"]:
        for b in ["rp", "rt"]:
            auto_close.append((a, b))
    auto_close.append(("optgroup", "optgroup"))
    for b in ["optgroup", "option"]:
        auto_close.append(("option", b))
    for a in formatting:
        for b in ["tr"] + lists + ["dd", "dt", "p"]:
            auto_close.append((a, b))
    for a in ["o:p", "p"]:
        for b in ["o:p", "p"]:
            auto_close.append((a, b))
    for a in leaves:
        contained.append((a, "table"))
    contained.append(("tr", "table"))
    for a in sections:
        contained.append((a, "table"))
    for b in ["ul", "ol"]:
        contained.append(("li", b))
    for a in ["dd", "dt"]:
        contained.append((a, "dl"))
    for a in ["rt", "rp"]:
        contained.append((a, "ruby"))
    for a in formatting:
        for b in ["td", "th"]:
            contained.append((a, b))
    auto_close.append(("marquee", "marquee"))

    def emit_pairs(const_name, pairs):
        conv = sorted(
            (rust_variant(keyword_of(a, entries)), rust_variant(keyword_of(b, entries)))
            for a, b in pairs
        )
        conv.sort(key=lambda pair: (order[pair[0]], order[pair[1]]))
        lines.append(f"pub const {const_name}: [(Keyword, Keyword); {len(conv)}] = [")
        for a, b in conv:
            lines.append(f"    (Keyword::{a}, Keyword::{b}),")
        lines.append("];")
        lines.append("")

    emit_pairs("AUTO_CLOSE", auto_close)
    emit_pairs("CONTAINED", contained)
    open(out, "w").write("\n".join(lines))


def main():
    entries = parse_gperf()
    check_enum_order(entries)
    print(f"keywords: {len(entries)}")
    gen_name(entries, "crates/ps-html/src/name_generated.rs")
    singles, multis = parse_escape_tables()
    print(f"single-byte entities: {len(singles)}, multi-byte: {len(multis)}")
    sets = parse_tag_sets()
    for key, members in sets.items():
        print(f"{key}: {len(members)}")
    gen_keywords(singles, multis, sets, entries, "crates/ps-html/src/keywords_generated.rs")


if __name__ == "__main__":
    main()
