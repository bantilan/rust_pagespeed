#!/usr/bin/env python3
"""Translates resource_tag_scanner_test.cc ValidateNoChanges blocks into a
Rust case table. Special-setup TEST_Fs (attribute-count loops, options
configuration) are skipped for hand ports.
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from translate_parse_tests import cxx_arg_to_bytes, rust_bytes, split_args

# Whole TEST_Fs needing hand ports (generated loops / options setup).
SKIP_TESTS = {
    "ManyAttributes",
    "ImageUrlValuedAttribute",
    "ImageUrlValuedAttributeOverride",
}

SRC = "/home/gamingph/Projects/Rust/mod_pagespeed/net/instaweb/rewriter/resource_tag_scanner_test.cc"
OUT = os.path.join(
    os.path.dirname(os.path.abspath(__file__)),
    "..", "tests", "goldens", "generated_scanner.rs",
)

text = open(SRC).read()
tests = [(m.start(), m.group(1)) for m in re.finditer(r"TEST_F\(\w+,\s*(\w+)\)", text)]


def rust_str(value):
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'

cases = []
skipped = []
for index, (start, name) in enumerate(tests):
    end = tests[index + 1][0] if index + 1 < len(tests) else len(text)
    body = text[start:end]
    if name in SKIP_TESTS:
        skipped.append(name)
        continue
    # Split body at each ValidateNoChanges call; expectations follow each.
    blocks = re.split(r"ValidateNoChanges\(", body)[1:]
    if not blocks:
        skipped.append(name + " (no blocks)")
        continue
    for block in blocks:
        depth = 1
        instr = False
        k = 0
        while depth > 0:
            c = block[k]
            if instr:
                if c == '"' and block[k - 1] != "\\":
                    instr = False
            else:
                if c == '"':
                    instr = True
                elif c == "(":
                    depth += 1
                elif c == ")":
                    depth -= 1
            k += 1
        args = split_args(block[: k - 1])
        if len(args) != 2:
            raise ValueError(f"{name}: expected 2 args, got {len(args)}")
        ident = cxx_arg_to_bytes(args[0]).decode("ascii")
        html = cxx_arg_to_bytes(args[1])
        rest = block[k:]
        urls = re.findall(r'EXPECT_STREQ\("((?:[^"\\]|\\.)*)", resources_\[(\d+)\]\)', rest)
        cats = re.findall(r"EXPECT_EQ\(semantic_type::k(\w+), resource_category_\[(\d+)\]\)", rest)
        # Stop urls/cats at the next ValidateNoChanges (handled by split).
        pairs = {}
        for raw, idx in urls:
            pairs.setdefault(int(idx), {})["url"] = cxx_arg_to_bytes(f'"{raw}"')
        for cat, idx in cats:
            pairs.setdefault(int(idx), {})["cat"] = cat
        ordered = [pairs[i] for i in sorted(pairs)]
        # Every pair needs both halves; empty expectation allowed.
        for pair in ordered:
            if "url" not in pair or "cat" not in pair:
                raise ValueError(f"{name}/{ident}: partial pair {pair}")
        cases.append((f"{name}::{ident}", html, [(p["url"], p["cat"]) for p in ordered]))

lines = [
    "//! GENERATED by tool/translate_scanner_tests.py — do not edit.",
    "//! (case, html, [(decoded url, category)]) translated from",
    "//! resource_tag_scanner_test.cc ValidateNoChanges blocks.",
    "",
    "#[allow(dead_code)]",
    "pub const CASES: &[(&str, &[u8], &[(&[u8], &str)])] = &[",
]
for ident, html, pairs in cases:
    lines.append(f"    ({rust_str(ident)}, {rust_bytes(html)}, &[")
    for url, cat in pairs:
        lines.append(f"        ({rust_bytes(url)}, {rust_str(cat)}),")
    lines.append("    ]),")
lines.append("];")
lines.append("")
open(OUT, "w").write("\n".join(lines))
print(f"translated {len(cases)} blocks, skipped {len(skipped)}: {skipped}")
